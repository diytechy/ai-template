#!/usr/bin/env python3
"""Generate the per-review-scope verdict rollups — `docs/reviews/rollup/<train>.md`.

WHY IT IS GENERATED (OI-76, ruled 2026-08-31). The per-WI rollup used to be the
merge gate's ONLY input, and it was hand-authored: nothing in the kit wrote it,
it restated the round files in prose, and anyone with commit access could author
one. The ruling split those roles apart. The gate now computes over the round
files a logged reviewer session produced (`kitlib.verdict`), and the rollup
survives as what it was always genuinely good for — a HUMAN READING of a lane's
review history in one file — under the kit's own rule for that shape:
**generated, not hand-maintained**. Declared in `docs/stack.ini [generated]`,
freshness-gated by `--check`, never read by the gate.

ONE FILE PER TRAIN, NOT PER WI, and that is the review scope rather than a
convenience. A traincar is ONE review scope (LLR-140): a worker schedules its
round only once every assigned WI is built, and the round covers the combined
train diff — a per-WI slice of a round never existed, so a per-WI rollup would
have to invent one.

WHAT IT DELIBERATELY DOES NOT SAY. It never names a governing verdict. Governing
is TREE IDENTITY, which is a question about a branch's current tree and can only
be answered against a repository at a moment; writing an answer into a checked-in
file would recreate exactly the artifact the ruling retired — a stale summary
that reads as authority. Every row here is a fact about a FILE, so the rollup is
deterministic from the tree and `--check` means what it says.

Stack-agnostic, standard library only (Python 3.11+, Windows/POSIX).

Usage:
    python scripts/gen_verdict_rollup.py            # write docs/reviews/rollup/
    python scripts/gen_verdict_rollup.py --check    # exit 1 if any file is stale
    python scripts/gen_verdict_rollup.py --root .   # repository root
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import score_reviews  # noqa: E402  (path set above; the script-sibling idiom)
from kitlib import verdict as kverdict  # noqa: E402

REVIEWS = "docs/reviews"
ROLLUP_DIR = REVIEWS + "/rollup"

HEADER = """<!-- GENERATED by scripts/gen_verdict_rollup.py — do not hand-edit.
     Declared in docs/stack.ini [generated]; `--check` gates its freshness. -->

# Review rounds — `{train}`

Every round file this review scope carries, newest last. **The merge gate does
not read this file.** It computes its predicate over the round files themselves,
restricted to rounds a logged reviewer session produced, and a verdict counts
only when it names the branch's current non-record tree (OI-76, governing = tree
identity). This is the human's reading of the same evidence.

| # | phase | reviewed | verdict | findings | file |
|---|---|---|---|---|---|
"""


def train_dirs(root):
    """Every review-scope directory under `docs/reviews/` that holds a round
    file, sorted. The generated `rollup/` subtree is not one of them."""
    home = Path(root) / REVIEWS
    if not home.is_dir():
        return []
    found = []
    for child in sorted(p for p in home.iterdir() if p.is_dir()):
        if child.name == "rollup":
            continue
        if any(kverdict.round_file(_rel(root, p)) for p in child.iterdir()):
            found.append(child)
    return found


def _rel(root, path):
    return Path(path).relative_to(Path(root)).as_posix()


def render(root, train_dir):
    """The rollup text for one review scope."""
    rows = []
    for path in sorted(train_dir.iterdir()):
        parsed = kverdict.round_file(_rel(root, path))
        if not parsed:
            continue
        _train, ordinal, phase, sha = parsed
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        v = score_reviews.parse_verdict(text)
        rows.append(
            "| {} | {} | `{}` | {} | {} | `{}` |".format(
                ordinal,
                phase,
                sha,
                v.verdict or "(unparseable)",
                len(v.findings),
                path.name,
            )
        )
    return HEADER.format(train=train_dir.name) + "\n".join(rows) + "\n"


def targets(root):
    """`[(output path, text)]` for every review scope, in a stable order."""
    return [
        (Path(root) / ROLLUP_DIR / (d.name + ".md"), render(root, d))
        for d in train_dirs(root)
    ]


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--root", default=".", help="repository root (default: cwd)")
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if any rollup is stale"
    )
    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    wanted = targets(root)
    if args.check:
        # Compared on NORMALIZED line endings: a CRLF checkout is not a stale
        # rollup. An EXTRA file in the tree is stale too — a retired review
        # scope that keeps its rollup is the same lie as an out-of-date one.
        stale = [
            p
            for p, text in wanted
            if not p.is_file()
            or p.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
            != text
        ]
        home = root / ROLLUP_DIR
        known = {p for p, _t in wanted}
        stale += [
            p for p in sorted(home.glob("*.md")) if p not in known and p not in stale
        ]
        if not stale:
            print("gen_verdict_rollup: fresh ({} review scope(s)).".format(len(wanted)))
            return 0
        print(
            "gen_verdict_rollup: STALE — {}. Run `python "
            "scripts/gen_verdict_rollup.py` and commit the result.".format(
                ", ".join(_rel(root, p) for p in stale)
            ),
            file=sys.stderr,
        )
        return 1
    (root / ROLLUP_DIR).mkdir(parents=True, exist_ok=True)
    for path, text in wanted:
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(
        "gen_verdict_rollup: wrote {} rollup(s) under {}.".format(
            len(wanted), ROLLUP_DIR
        )
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI
    raise SystemExit(main())
