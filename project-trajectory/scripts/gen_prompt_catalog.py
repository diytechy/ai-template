#!/usr/bin/env python3
"""Generate the shipped prompt catalogue — `project-trajectory/prompts/CATALOG.md`.

WHY A GENERATED CATALOGUE. Plan §8 moved the loop's session prompts out of
Python constants and into reviewable files, on the argument that *prose steers
the automation* and therefore has to be diffable. That gets you a reviewable
template. It does not get you an answer to the two questions an operator
actually asks when a session behaves oddly:

    which template did that session use, and was it the one I am reading?

This catalogue is half of that answer. It lists every shipped prompt with its
file, its `{slot}` names, and the digest of its normalized text. The other half
is `agent_common.write_session_log`, which records the same digest per session
(`# prompt-sha:`), so a row and a template can be matched without keeping every
rendered prompt on disk — and a template edit shows up as a hash change across
otherwise identical rows.

FRESHNESS IS GATED, not hoped for. `--check` exits 1 when the file on disk
disagrees with what this script would write, the same contract
`gen_arch_map.py --check` and `gen_skills_index.py --check` hold: a generated
artifact nobody re-generates is a document that lies, and a lying catalogue is
worse than none because it invites the operator to conclude the wrong thing
about a session they are debugging.

Stack-agnostic, standard library only (Python 3.11+, Windows/POSIX).

Usage:
    python scripts/gen_prompt_catalog.py            # write prompts/CATALOG.md
    python scripts/gen_prompt_catalog.py --check    # exit 1 if stale
    python scripts/gen_prompt_catalog.py --print    # write nothing, print it
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import prompts  # noqa: E402  (path set above; the kit's script-sibling idiom)

CATALOG = prompts.PROMPTS / "CATALOG.md"

HEADER = """<!-- GENERATED by scripts/gen_prompt_catalog.py — do not hand-edit.
     Re-generate after editing any template; `--check` gates it. -->

# Shipped prompt catalogue

Every prompt this kit ships, with its `{slot}` names and the digest of its
normalized text (line endings folded, trailing newline dropped — the same
template checked out CRLF and LF is the same prompt).

**The digest is the join key.** Each session log records `# prompt-sha:` for the
prompt it actually launched, so "which template did this session use" is a
lookup rather than an inference. A rendered prompt's digest differs from its
template's whenever slots were filled — that is the point: the template row
below identifies the SOURCE, the session row identifies the RESULT.

Slots are filled strictly: an unknown slot, or a declared slot left unfilled,
is a refusal rather than a silently empty instruction.

| Key | File | Digest | Slots |
|---|---|---|---|
"""

FOOTER = """
An operator override replaces a template per phase (`--prompt-map`); an
overridden session's `# prompt-template:` names the override path, so the
substitution is visible in the telemetry rather than only in the launch flags.
"""


def render():
    """The catalogue's full text. Pure — takes no arguments and touches no
    state beyond reading the shipped templates, so `--check` and the write path
    cannot disagree about what "current" means.

    Implements: SR-146, LLR-164
    """
    rows = [
        "| `{key}` | [{file}]({file}) | `{digest}` | {slots} |".format(
            key=key,
            file=filename,
            digest=digest,
            slots=", ".join("`{{{}}}`".format(s) for s in slot_names.split(";") if s)
            or "—",
        )
        for key, filename, slot_names, digest in prompts.catalog_rows()
    ]
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main(argv=None):
    prompts._utf8_console()
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if prompts/CATALOG.md is stale (CI / gate use)",
    )
    ap.add_argument(
        "--print", dest="show", action="store_true", help="print, write nothing"
    )
    args = ap.parse_args(argv)
    text = render()
    if args.show:
        print(text, end="")
        return 0
    if args.check:
        current = (
            CATALOG.read_text(encoding="utf-8", errors="replace")
            if CATALOG.is_file()
            else ""
        )
        # Compared on NORMALIZED line endings, for the same reason the digest is
        # taken that way: a CRLF checkout is not a stale catalogue.
        if current.replace("\r\n", "\n") == text:
            print("gen_prompt_catalog: fresh ({} prompts).".format(text.count("\n| `")))
            return 0
        print(
            "gen_prompt_catalog: {} is STALE — a template changed and the "
            "catalogue did not. Run `python scripts/gen_prompt_catalog.py` "
            "and commit the result.".format(
                CATALOG.relative_to(prompts.KIT.parent)
                if CATALOG.is_relative_to(prompts.KIT.parent)
                else CATALOG
            ),
            file=sys.stderr,
        )
        return 1
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    with CATALOG.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("gen_prompt_catalog: wrote {}.".format(CATALOG))
    return 0


if __name__ == "__main__":
    sys.exit(main())
